#!/usr/bin/env node
/**
 * 零依赖 Client 拼装脚本：将 `src/client/*` 源码按依赖顺序拼装为 DSH 单文件包 `client.js`。
 *
 * 为什么需要它：DSH `clientModules` 仅加载单个自包含文件，不允许浏览器端相对 import；
 * 但开发维护把 2800+ 行塞在一个文件极难演进，因此用本脚本零依赖、确定性地从 `src/client/` 产出 `client.js`。
 *
 * 用法：
 * - `node scripts/build-client.mjs`          生成 `client.js`
 * - `node scripts/build-client.mjs --check`  校验仓库中的 `client.js` 是否与 `src/client/` 同步
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const CLIENT_DIR = join(ROOT, 'src', 'client')
const OUTPUT = join(ROOT, 'client.js')

const PARTS = [
  'constants.js',
  'i18n/zh.js',
  'i18n/en.js',
  'components/primitives.js',
  'components/mode-chip.js',
  'tabs/modes-tab.js',
  'tabs/prompts-tab.js',
  'tabs/workflow-tab.js',
  'tabs/remote-tab.js',
  'entry.js',
]

function indent(text, spaces = 4) {
  const pad = ' '.repeat(spaces)
  return text
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map(line => (line === '' ? '' : `${pad}${line}`))
    .join('\n')
}

export function buildClientSource() {
  const cssRaw = readFileSync(join(CLIENT_DIR, 'styles.css'), 'utf8').replace(/\r\n/g, '\n')
  const sections = PARTS.map((rel) => {
    const body = readFileSync(join(CLIENT_DIR, rel), 'utf8').replace(/\r\n/g, '\n').trim()
    return `/* === src/client/${rel} === */\n${body}`
  })

  return [
    '/* AUTO-GENERATED by scripts/build-client.mjs — edit files under src/client/ instead. */',
    'window.__ModuleLoader__.load({',
    "  id: 'dsh-flow',",
    '  factory: (require) => {',
    '    var module = { exports: {} }',
    '    var exports = module.exports',
    '',
    "    const React = require('react')",
    "    const ReactDOM = require('react-dom')",
    '    const h = React.createElement',
    '    const { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState } = React',
    '    const { createPortal } = ReactDOM',
    '',
    `    const CSS = ${JSON.stringify(cssRaw)}`,
    '',
    indent(sections.join('\n\n'), 4),
    '',
    '    return module.exports',
    '  },',
    '})',
    '',
  ].join('\n')
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const checkMode = process.argv.includes('--check')
  const built = buildClientSource()
  if (checkMode) {
    let existing = ''
    try { existing = readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') } catch { existing = '' }
    if (existing !== built) {
      console.error('client.js 与 src/client/ 不同步，请运行 `npm run build:client`')
      process.exit(1)
    }
    console.log('OK: client.js 与 src/client/ 保持一致')
  } else {
    writeFileSync(OUTPUT, built, 'utf8')
    console.log(`Built client.js (${Buffer.byteLength(built, 'utf8')} bytes)`)
  }
}
